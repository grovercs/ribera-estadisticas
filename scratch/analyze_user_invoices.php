$lines = explode("\n", $text);
$invoices = [];
foreach ($lines as $line) {
    $line = trim($line);
    if (empty($line)) continue;
    $parts = preg_split('/\s+/', $line);
    if (!empty($parts[0])) {
        $invoices[] = trim($parts[0]);
    }
