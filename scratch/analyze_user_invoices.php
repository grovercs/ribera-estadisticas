echo "Total invoices in list: " . count($invoices) . "\n";

// Let's check which stores and payment forms these invoices belong to, and their pending status.
$placeholders = implode(',', array_fill(0, count($invoices), '?'));
$res = $db->select("
    SELECT 
        v.cod_forma_liquidacion,
        SUBSTRING(CAST(v.cod_factura AS VARCHAR), 3, 1) as store_char,
        COUNT(*) as cnt,
        SUM(v.importe - v.importe_cobrado) as total_pend
    FROM vencimientos_facturas v
    WHERE v.cod_factura IN ($placeholders)
    GROUP BY v.cod_forma_liquidacion, SUBSTRING(CAST(v.cod_factura AS VARCHAR), 3, 1)
", $invoices);

echo "\n=== Breakdown of the user's list in DB ===\n";
foreach ($res as $r) {
    echo "  Store Char: {$r->store_char} | FP: {$r->cod_forma_liquidacion} | Count: {$r->cnt} | Sum: " . number_format($r->total_pend, 2) . "\n";
}

// Check how many of them have Z-FPs vs regular ones
